'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createResearch } = require('../sidecar/eyehold-research.js');
const { createVentures } = require('../sidecar/eyehold-ventures.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eyehold-research-'));
const research = createResearch({ file: path.join(root, 'research.json'), now: () => 't' });
const ventures = createVentures({ file: path.join(root, 'ventures.json'), now: () => 't' });
const asked = research.requestOpportunities({ managerId: 'eye', question: 'Best lawful ways to earn the first dollar.' });
const brief = { rank: 1, title: 'Printable planners', ventureType: 'etsy-shop', expectedRevenueCents: 20000, upfrontCostCents: 500, risk: 'medium', timeToFirstDollarDays: 21, sources: ['Etsy search: planner'] };
assert.throws(() => research.fileBriefs({ requestId: asked.id, researcherId: 'raven', briefs: [{ ...brief, sources: [] }] }), /sources/);
const filed = research.fileBriefs({ requestId: asked.id, researcherId: 'raven', briefs: [brief, { ...brief, rank: 2, title: 'Logo kits', risk: 'low', timeToFirstDollarDays: 14 }] });
assert.equal(filed.briefs[0].rank, 1);
assert.equal(filed.briefs[0].status, 'filed');
assert.throws(() => research.openFromBrief({ requestId: asked.id, rank: 1, agentId: 'moonleaf', ventures }), /accepted brief/);
research.acceptBrief({ requestId: asked.id, rank: 1, managerId: 'eye' });
const opened = research.openFromBrief({ requestId: asked.id, rank: 1, agentId: 'moonleaf', ventures });
assert.equal(opened.assignment.ventureId, 'etsy-shop');
assert.equal(opened.attribution.sharePercent, 20);
assert.equal(opened.attribution.researcherId, 'raven');
const follow = research.requestForVenture({ agentId: 'moonleaf', ventureId: 'etsy-shop', topic: 'trending Etsy niches and pricing' });
assert.equal(research.queue().requests.length, 1);
const answer = research.attachFindings({ requestId: follow.id, researcherId: 'raven', findings: 'Planners still sell; price near 8 dollars.', sources: ['Etsy category page'] });
assert.equal(answer.status, 'answered');
assert.equal(answer.ventureId, 'etsy-shop');
assert.equal(research.queue().requests.length, 0);
fs.rmSync(root, { recursive: true, force: true });
console.log('Research briefs stay estimates until the Manager assigns a venture');
