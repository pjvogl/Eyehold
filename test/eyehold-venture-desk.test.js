'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createVentureDesk } = require('../sidecar/eyehold-venture-desk.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eyehold-desk-'));
const desk = createVentureDesk({ file: path.join(root, 'desk.json'), now: () => 't' });
const item = desk.produce({ ventureId: 'etsy-shop', artifact: 'Printable planner page.' });
assert.equal(item.status, 'draft');
assert.throws(() => desk.queueOutward({ id: item.id, kind: 'listing', confirmed: true }), /Silver Bough/);
assert.equal(desk.review({ id: item.id, approved: true }).status, 'reviewed');
assert.throws(() => desk.queueOutward({ id: item.id, kind: 'listing', confirmed: false }), /owner-confirmation-required/);
assert.equal(desk.queueOutward({ id: item.id, kind: 'listing', confirmed: true }).status, 'queued-outward');
const trade = desk.produce({ ventureId: 'trader', artifact: 'Paper plan for a small position.' });
desk.review({ id: trade.id, approved: true });
assert.throws(() => desk.queueOutward({ id: trade.id, kind: 'listing', confirmed: true }), /only queues a trade/);
assert.equal(desk.queueOutward({ id: trade.id, kind: 'trade', confirmed: true }).outward, 'trade');
fs.rmSync(root, { recursive: true, force: true });
console.log('Etsy and trader work pass Deepforge, Silver Bough, then an owner click at Iron Host');
