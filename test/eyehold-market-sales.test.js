'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createFinanceStore } = require('../sidecar/eyehold-finance-store.js');
const { settleReviewedSale } = require('../sidecar/eyehold-market-sales.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eyehold-sale-'));
const store = createFinanceStore({ file: path.join(root, 'finance.json'), now: () => '2026-11-10T00:00:00.000Z' });
const sale = { id: 'stripe:pi_test_1', verified: true, livemode: false, currency: 'USD', cents: 1000, computeCents: 200 };
assert.throws(() => settleReviewedSale(store, sale), /operator review/);
assert.equal(store.snapshot().netProfitUSD, null);
const settled = settleReviewedSale(store, sale, { confirmedReviewed: true });
assert.equal(settled.netProfitUSD, 8);
assert.equal(settled.crownsAwarded, 0);
assert.deepEqual(settled.unlockedMilestonesUSD, []);
const second = settleReviewedSale(store, { ...sale, id: 'stripe:pi_test_2', cents: 500, computeCents: 0 }, { confirmedReviewed: true });
assert.equal(second.netProfitUSD, 13);
assert.throws(() => settleReviewedSale(store, { ...sale, id: 'stripe:pi_test_3', computeCents: null }, { confirmedReviewed: true }), /not measured/);
assert.equal(store.snapshot().netProfitUSD, 13);
assert.throws(() => settleReviewedSale(store, { ...sale, livemode: true }, { confirmedReviewed: true }), /test-mode/);
fs.rmSync(root, { recursive: true, force: true });
console.log('Reviewed sales enter the ladder as revenue minus measured compute');
