'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createVentureScore } = require('../sidecar/eyehold-venture-score.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eyehold-score-'));
const score = createVentureScore({ file: path.join(root, 'score.json') });
const shop = score.creditVerified({ agentId: 'moonleaf', ventureId: 'etsy-shop', revenueCents: 2500, computeCents: 200, otherCostCents: 150 });
assert.equal(shop.netCents, 2150);
assert.equal(shop.crowns, 21);
const paper = score.creditPractice({ agentId: 'forge', ventureId: 'trader', paperPnlCents: 18000 });
assert.equal(paper.crowns, 0);
assert.equal(paper.practicePoints, 180);
assert.equal(score.board().find(item => item.ventureId === 'trader').practiceIsCrowns, false);
assert.throws(() => score.creditVerified({ agentId: 'moonleaf', ventureId: 'etsy-shop', revenueCents: 100, computeCents: null, otherCostCents: 0 }), /compute/);
const loss = score.creditVerified({ agentId: 'moonleaf', ventureId: 'etsy-shop', revenueCents: 0, computeCents: 5000, otherCostCents: 0 });
assert.equal(loss.netCents, 2150 - 5000);
assert.equal(loss.crowns, 0);
fs.rmSync(root, { recursive: true, force: true });
console.log('Crowns follow verified net profit; paper results stay practice points');
