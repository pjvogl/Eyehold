'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createVentures, BUILTINS, MANAGER_GOAL } = require('../sidecar/eyehold-ventures.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eyehold-ventures-'));
const ventures = createVentures({ file: path.join(root, 'ventures.json'), now: () => 't' });
assert.deepEqual(BUILTINS.map(item => item.id), ['etsy-shop', 'digital-services', 'trader']);
assert.match(MANAGER_GOAL, /verified net profit/);
assert.match(MANAGER_GOAL, /Paper trading is practice/);
const shop = ventures.assign({ agentId: 'moonleaf', ventureId: 'etsy-shop' });
assert.equal(shop.status, 'active');
assert.throws(() => ventures.assign({ agentId: 'forge', ventureId: 'casino' }), /unknown venture/);
const proposed = ventures.proposeType({ managerId: 'eye', name: 'Print studio', summary: 'Sell printable planners the owner approves.' });
assert.equal(proposed.status, 'queued');
assert.throws(() => ventures.assign({ agentId: 'forge', ventureId: proposed.id }), /unknown venture/);
assert.throws(() => ventures.approveType(proposed.id, { confirmed: false }), /owner-confirmation-required/);
assert.equal(ventures.board().proposals.length, 1);
ventures.approveType(proposed.id, { confirmed: true });
assert.equal(ventures.assign({ agentId: 'forge', ventureId: proposed.id }).status, 'active');
assert.throws(() => ventures.retire({ agentId: 'moonleaf', ventureId: 'etsy-shop', confirmed: false }), /owner-confirmation-required/);
assert.equal(ventures.retire({ agentId: 'moonleaf', ventureId: 'etsy-shop', confirmed: true }).status, 'retired');
assert.equal(ventures.board().assignments.some(item => item.agentId === 'moonleaf'), false);
fs.rmSync(root, { recursive: true, force: true });
console.log('Manager can assign built-in ventures and owner-approved new types');
