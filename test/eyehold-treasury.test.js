'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createTreasury } = require('../sidecar/eyehold-treasury.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eyehold-treasury-'));
const treasury = createTreasury({ file: path.join(root, 'treasury.json'), now: () => 't' });
assert.throws(() => treasury.creditEarned(500, { verified: false }), /verified/);
assert.equal(treasury.snapshot().availableCents, 0);
treasury.creditEarned(1000, { verified: true });
assert.throws(() => treasury.topUp(250, { confirmed: false }), /owner-confirmation-required/);
treasury.topUp(250, { confirmed: true });
assert.equal(treasury.snapshot().availableCents, 1250);
assert.throws(() => treasury.setCap({ agentId: 'moonleaf', ventureId: 'etsy-shop', capCents: 400, confirmed: false }), /owner-confirmation-required/);
treasury.setCap({ agentId: 'moonleaf', ventureId: 'etsy-shop', capCents: 400, confirmed: true });
const fee = treasury.requestSpend({ agentId: 'moonleaf', ventureId: 'etsy-shop', cents: 150, kind: 'listing-fee', note: 'listing' });
assert.equal(fee.status, 'queued');
assert.equal(treasury.snapshot().availableCents, 1250);
assert.throws(() => treasury.approveSpend(fee.id, { confirmed: false }), /owner-confirmation-required/);
assert.equal(treasury.approveSpend(fee.id, { confirmed: true }).treasury.availableCents, 1100);
const overCap = treasury.requestSpend({ agentId: 'moonleaf', ventureId: 'etsy-shop', cents: 300, kind: 'ad-spend', note: 'ads' });
assert.throws(() => treasury.approveSpend(overCap.id, { confirmed: true }), /hard cap/);
assert.equal(treasury.snapshot().availableCents, 1100);
const broke = treasury.requestSpend({ agentId: 'moonleaf', ventureId: 'etsy-shop', cents: 2000, kind: 'tool', note: 'tool' });
treasury.setCap({ agentId: 'moonleaf', ventureId: 'etsy-shop', capCents: 5000, confirmed: true });
assert.throws(() => treasury.approveSpend(broke.id, { confirmed: true }), /cannot fund/);
fs.rmSync(root, { recursive: true, force: true });
console.log('Treasury spends only approved amounts inside earned cash and hard caps');
